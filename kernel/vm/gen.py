import hashlib, hmac, struct, sys

ROOT_KEY = bytes(range(32))

def token(rights, issued, expires, device=b'\xab'*16, nonce=b'\xcd'*32, base=1, ver=1):
    b = bytearray()
    b.append(ver)
    b += device
    b += struct.pack(">I", rights)
    b += struct.pack(">Q", issued)
    b += struct.pack(">Q", expires)
    b += struct.pack(">Q", base)
    b += nonce
    assert len(b) == 77, len(b)
    return bytes(b)

def tag(tok, key=ROOT_KEY):
    return hmac.new(key, tok, hashlib.sha256).digest()

# A clock far in the future/past so the VM's clock lands inside the window.
issued, expires = 1_600_000_000, 4_000_000_000

cases = {}
cases['valid']      = token(0x01, issued, expires)
cases['expired']    = token(0x01, issued, 1_700_000_000)
cases['not_yet']    = token(0x01, 3_000_000_000, 4_000_000_000)
cases['zero_right'] = token(0x00, issued, expires)
cases['bad_ver']    = token(0x01, issued, expires, ver=2)

out = ['/* generated by gen.py: token bytes and HMAC-SHA256 tags from python hashlib */',
       '#ifndef CASES_H', '#define CASES_H', '#include <stdint.h>', '']
for name, tok in cases.items():
    out.append(f'static const uint8_t {name}_tok[77] = {{')
    out.append(','.join(str(x) for x in tok))
    out.append('};')
    t = tag(tok)
    out.append(f'static const uint8_t {name}_tag[32] = {{')
    out.append(','.join(str(x) for x in t))
    out.append('};')
    out.append('')

# valid token with the tag corrupted in the last byte
bad = bytearray(tag(cases['valid'])); bad[31] ^= 0xFF
out.append('static const uint8_t badtag_tag[32] = {')
out.append(','.join(str(x) for x in bad))
out.append('};')
out.append('#endif')
open('cases.h','w').write('\n'.join(out))
print("wrote cases.h")
print("valid tag:", tag(cases['valid']).hex())
