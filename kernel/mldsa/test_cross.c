static const uint8_t MSG[] = "sovereign capability grant v1";

/* verify_only.c exposes only the internal entry point (the public wrapper with its 257-byte
 * stack buffer is not built for the kernel). Build the FIPS 204 prefix here instead. */
static int local_verify(const uint8_t *sig, size_t siglen, const uint8_t *m, size_t mlen,
                        const uint8_t *ctx, size_t ctxlen, const uint8_t *pk)
{
  uint8_t pre[257];
  size_t i;

  if (ctxlen > 255)
    return -1;
  pre[0] = 0;
  pre[1] = (uint8_t)ctxlen;
  for (i = 0; i < ctxlen; i++)
    pre[2 + i] = ctx[i];
  return crypto_sign_verify_internal(sig, siglen, m, mlen, pre, 2 + ctxlen, pk);
}

int main(void)
{
uint8_t ctx[1] = { 0 };

printf("vk len %zu (want %d)\n", sizeof VK, CRYPTO_PUBLICKEYBYTES);
printf("sig len %zu (want %d)\n", sizeof SIG, CRYPTO_BYTES);
printf("msg: %s\n", MSG);

int rc = local_verify(SIG, sizeof SIG, MSG, strlen((const char *)MSG), NULL, 0, VK);
printf("verify with empty ctx: rc=%d\n", rc);
if (rc == 0) {
/* A verifier that accepts everything would also print rc=0. Prove it rejects a
 * corrupted signature and a wrong message before declaring success. */
uint8_t bad[sizeof SIG];

memcpy(bad, SIG, sizeof SIG);
bad[100] ^= 0x01;
if (local_verify(bad, sizeof bad, MSG, strlen((const char *)MSG), NULL, 0, VK) == 0) {
printf("RESULT: crossimpl FAILED (accepted a corrupted signature)\n");
return 1;
}
printf("ok   corrupted signature rejected\n");

if (local_verify(SIG, sizeof SIG, (const uint8_t *)"other message", 13, NULL, 0,
       VK) == 0) {
printf("RESULT: crossimpl FAILED (accepted a wrong message)\n");
return 1;
}
printf("ok   wrong message rejected\n");

memcpy(bad, VK, sizeof VK);
bad[40] ^= 0x01;
if (local_verify(SIG, sizeof SIG, MSG, strlen((const char *)MSG), NULL, 0, bad) == 0) {
printf("RESULT: crossimpl FAILED (accepted a corrupted public key)\n");
return 1;
}
printf("ok   corrupted public key rejected\n");

printf("RESULT: crossimpl passed\n");
return 0;
}

/* Try the other plausible convention in case the crate omits the context prefix. */
rc = local_verify(SIG, sizeof SIG, MSG, strlen((const char *)MSG), ctx, 0, VK);
printf("verify with explicit empty ctx: rc=%d\n", rc);
printf("RESULT: crossimpl FAILED\n");
return 1;
}
